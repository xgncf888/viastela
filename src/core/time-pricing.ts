export interface TimePricingConfig {
  /** Monthly after-tax take-home income in CNY (e.g. 20000) */
  monthlyNetIncomeCny: number;
  /** Partner's monthly after-tax income in CNY for couple combined pool (optional) */
  partnerMonthlyNetIncomeCny: number;
  /** Whether to compute with the combined couple income pool */
  includePartnerInPool: boolean;
  /** Standard working days per month (default 21.75) */
  workDaysPerMonth: number;
  /** Contractual hours per work day (default 8) */
  dailyContractHours: number;
  /** Average unpaid overtime / after-hours message handling per work day (default 1.0) */
  dailyOvertimeHours: number;
  /** Round-trip daily commute time in minutes (default 60) */
  dailyCommuteMinutes: number;
  /** Daily post-work decompression / recovery time in minutes needed because of work exhaustion (default 30) */
  dailyDecompressionMinutes: number;
  /** Monthly expenses incurred purely because of work: commute transit, work lunches, coffee, work attire (default 0) */
  monthlyWorkExpenseCny: number;
  /** Multiplier for deep focus / study / compounding skill building (default 2.0x) */
  focusCompoundMultiplier: number;
  /** Target hourly rate aspiration in CNY (default 200) */
  targetHourlyCny: number;
  updatedAt: string;
}

export interface HourlyRateBreakdown {
  /** Total monthly income included in calculation */
  grossPoolIncomeCny: number;
  /** True net disposable income after subtracting work-related expenses */
  trueNetMonthlyIncomeCny: number;
  /** Standard contractual monthly hours (workDays * dailyContractHours) */
  nominalMonthlyHours: number;
  /** Total real life hours consumed by work (contract + overtime + commute + decompression) */
  trueMonthlyHours: number;
  /** Hidden extra hours spent per month due to overtime, commute, and decompression */
  hiddenMonthlyHours: number;
  /** Percentage of total work-related time that is hidden/unbilled */
  hiddenHoursRatioPct: number;
  /** Paper / nominal hourly rate (Gross Pool ÷ Nominal Hours) */
  nominalHourlyCny: number;
  /** True net life-energy hourly rate ((Gross Pool - Work Expenses) ÷ True Monthly Hours) */
  trueNetHourlyCny: number;
  /** Deep-focus compounding hourly rate (True Net Hourly × focusCompoundMultiplier) */
  focusCompoundHourlyCny: number;
  /** Value of 1 minute at True Net Hourly Rate */
  minuteRateCny: number;
  /** Value of 15 minutes (1 standard time block) at True Net Hourly Rate */
  quarterHourCny: number;
  /** Ratio of True Net Hourly Rate to Nominal Hourly Rate (0-100+) */
  effectiveRetentionPct: number;
  /** Hourly drag caused by hidden hours and work expenses */
  hourlyDragCny: number;
}

