function clampNonNegative(val: number, fallback = 0): number {
  if (!Number.isFinite(val) || val < 0) return fallback;
  return val;
}

export function computeHourlyRateBreakdown(config: TimePricingConfig): HourlyRateBreakdown {
  const baseIncome = clampNonNegative(config.monthlyNetIncomeCny, 0);
  const partnerIncome = config.includePartnerInPool
    ? clampNonNegative(config.partnerMonthlyNetIncomeCny, 0)
    : 0;
  const grossPoolIncomeCny = baseIncome + partnerIncome;

  const workExpense = clampNonNegative(config.monthlyWorkExpenseCny, 0);
  const trueNetMonthlyIncomeCny = Math.max(0, grossPoolIncomeCny - workExpense);

  const workDays = Math.max(1, clampNonNegative(config.workDaysPerMonth, 21.75));
  const contractHoursPerDay = Math.max(0.5, clampNonNegative(config.dailyContractHours, 8));
  const overtimeHoursPerDay = clampNonNegative(config.dailyOvertimeHours, 0);
  const commuteHoursPerDay = clampNonNegative(config.dailyCommuteMinutes, 0) / 60;
  const decompressionHoursPerDay = clampNonNegative(config.dailyDecompressionMinutes, 0) / 60;

  const partnerMultiplier =
    config.includePartnerInPool && partnerIncome > 0 && baseIncome > 0 ? 2 : 1;

  const nominalMonthlyHours = workDays * contractHoursPerDay * partnerMultiplier;
  const hiddenDailyHours = overtimeHoursPerDay + commuteHoursPerDay + decompressionHoursPerDay;
  const hiddenMonthlyHours = workDays * hiddenDailyHours * partnerMultiplier;
  const trueMonthlyHours = Math.max(1, nominalMonthlyHours + hiddenMonthlyHours);

  const nominalHourlyCny =
    nominalMonthlyHours > 0 ? grossPoolIncomeCny / nominalMonthlyHours : 0;
  const trueNetHourlyCny =
    trueMonthlyHours > 0 ? trueNetMonthlyIncomeCny / trueMonthlyHours : 0;

  const multiplier = Math.max(1, clampNonNegative(config.focusCompoundMultiplier, 2.0));
  const focusCompoundHourlyCny = trueNetHourlyCny * multiplier;

  const minuteRateCny = trueNetHourlyCny / 60;
  const quarterHourCny = trueNetHourlyCny * 0.25;

  const hiddenHoursRatioPct =
    trueMonthlyHours > 0 ? Math.round((hiddenMonthlyHours / trueMonthlyHours) * 100) : 0;
  const effectiveRetentionPct =
    nominalHourlyCny > 0 ? Math.round((trueNetHourlyCny / nominalHourlyCny) * 100) : 0;
  const hourlyDragCny = Math.max(0, nominalHourlyCny - trueNetHourlyCny);

  return {
    grossPoolIncomeCny: Math.round(grossPoolIncomeCny * 100) / 100,
    trueNetMonthlyIncomeCny: Math.round(trueNetMonthlyIncomeCny * 100) / 100,
    nominalMonthlyHours: Math.round(nominalMonthlyHours * 10) / 10,
    trueMonthlyHours: Math.round(trueMonthlyHours * 10) / 10,
    hiddenMonthlyHours: Math.round(hiddenMonthlyHours * 10) / 10,
    hiddenHoursRatioPct,
    nominalHourlyCny: Math.round(nominalHourlyCny * 100) / 100,
    trueNetHourlyCny: Math.round(trueNetHourlyCny * 100) / 100,
    focusCompoundHourlyCny: Math.round(focusCompoundHourlyCny * 100) / 100,
    minuteRateCny: Math.round(minuteRateCny * 100) / 100,
    quarterHourCny: Math.round(quarterHourCny * 100) / 100,
    effectiveRetentionPct,
    hourlyDragCny: Math.round(hourlyDragCny * 100) / 100,
  };
}

export function computeExpenseLifeHours(
  amountCny: number,
  trueNetHourlyCny: number,
  dailyRealHours = 8,
): ExpenseLifeHours {
  const safeAmount = clampNonNegative(amountCny, 0);
  const safeHourly = clampNonNegative(trueNetHourlyCny, 0);

  if (safeHourly <= 0 || safeAmount <= 0) {
    return {
      amountCny: safeAmount,
      trueNetHourlyCny: safeHourly,
      totalHours: 0,
      wholeHours: 0,
      remainingMinutes: 0,
      totalMinutes: 0,
      workDaysEquivalent: 0,
      labelZh: safeHourly <= 0 ? '先设定真实时薪即可换算生命工时' : '0 分钟生命工时',
      labelEn: safeHourly <= 0 ? 'Set true hourly rate to convert' : '0m life hours',
    };
  }

  const totalHours = safeAmount / safeHourly;
  const totalMinutes = Math.round(totalHours * 60);
  const wholeHours = Math.floor(totalMinutes / 60);
  const remainingMinutes = totalMinutes % 60;
  const workDaysEquivalent = Math.round((totalHours / Math.max(1, dailyRealHours)) * 10) / 10;

  let labelZh = '';
  let labelEn = '';
  if (totalMinutes < 60) {
    labelZh = `约 ${totalMinutes} 分钟真实生命工时`;
    labelEn = `~${totalMinutes}m of true life work`;
  } else if (workDaysEquivalent >= 1.5) {
    labelZh = `约 ${totalHours.toFixed(1)} 小时（折合 ${workDaysEquivalent} 个真实工作日）`;
    labelEn = `~${totalHours.toFixed(1)}h (${workDaysEquivalent} workdays)`;
  } else {
    labelZh =
      remainingMinutes > 0
        ? `约 ${wholeHours} 小时 ${remainingMinutes} 分钟真实生命工时`
        : `约 ${wholeHours} 小时真实生命工时`;
    labelEn =
      remainingMinutes > 0
        ? `~${wholeHours}h ${remainingMinutes}m true life work`
        : `~${wholeHours}h true life work`;
  }

  return {
    amountCny: safeAmount,
    trueNetHourlyCny: safeHourly,
    totalHours: Math.round(totalHours * 100) / 100,
    wholeHours,
    remainingMinutes,
    totalMinutes,
    workDaysEquivalent,
    labelZh,
    labelEn,
  };
}

export function evaluateBuyTimeDecision(input: BuyTimeDecisionInput): BuyTimeDecisionResult {
  const costCny = clampNonNegative(input.costCny, 0);
  const savedMinutes = clampNonNegative(input.savedMinutes, 0);
  const baseRate = clampNonNegative(input.trueNetHourlyCny, 0);
  const compoundRate = clampNonNegative(input.focusCompoundHourlyCny ?? baseRate * 2, baseRate);
  const appliedHourlyRateCny = input.useCompoundRate ? compoundRate : baseRate;

  const savedHours = savedMinutes / 60;
  const timeValueSavedCny = Math.round(savedHours * appliedHourlyRateCny * 100) / 100;
  const netEvCny = Math.round((timeValueSavedCny - costCny) * 100) / 100;
  const costPerHourSavedCny =
    savedHours > 0 ? Math.round((costCny / savedHours) * 100) / 100 : Infinity;
  const roiPct = costCny > 0 ? Math.round(((timeValueSavedCny - costCny) / costCny) * 100) : 0;
  const isPositiveEv = appliedHourlyRateCny > 0 && savedMinutes > 0 && netEvCny >= 0;

  if (appliedHourlyRateCny <= 0) {
    return {
      costCny,
      savedMinutes,
      appliedHourlyRateCny: 0,
      timeValueSavedCny: 0,
      netEvCny: 0,
      costPerHourSavedCny: Number.isFinite(costPerHourSavedCny) ? costPerHourSavedCny : 0,
      roiPct: 0,
      isPositiveEv: false,
      verdictZh: '请先配置时薪基线',
      verdictEn: 'Configure hourly rate first',
      detailZh: '设定真实净时薪后，即可一键测算花钱买时间是否划算。',
      detailEn: 'Set your true net hourly rate to evaluate time-buying ROI.',
    };
  }

  if (isPositiveEv) {
    return {
      costCny,
      savedMinutes,
      appliedHourlyRateCny,
      timeValueSavedCny,
      netEvCny,
      costPerHourSavedCny,
      roiPct,
      isPositiveEv: true,
      verdictZh: `+EV 值得买 · 净赚 ¥${netEvCny.toFixed(1)} 时间价值`,
      verdictEn: `+EV Buy Time · Net +¥${netEvCny.toFixed(1)} value`,
      detailZh: `买下 1 小时仅花费 ¥${costPerHourSavedCny.toFixed(0)}，低于你的${
        input.useCompoundRate ? '深度复利时薪' : '真实净时薪'
      } ¥${appliedHourlyRateCny.toFixed(0)}/h（ROI ${roiPct >= 0 ? '+' : ''}${roiPct}%）`,
      detailEn: `Costs ¥${costPerHourSavedCny.toFixed(0)}/h saved vs your ¥${appliedHourlyRateCny.toFixed(0)}/h rate (ROI ${roiPct >= 0 ? '+' : ''}${roiPct}%)`,
    };
  }

  const lossAbs = Math.abs(netEvCny);
  return {
    costCny,
    savedMinutes,
    appliedHourlyRateCny,
    timeValueSavedCny,
    netEvCny,
    costPerHourSavedCny: Number.isFinite(costPerHourSavedCny) ? costPerHourSavedCny : 0,
    roiPct,
    isPositiveEv: false,
    verdictZh: `-EV 溢价偏高 · 折算多付 ¥${lossAbs.toFixed(1)}`,
    verdictEn: `-EV Premium · Overpaying ¥${lossAbs.toFixed(1)}`,
    detailZh: Number.isFinite(costPerHourSavedCny)
      ? `折合每小时花费 ¥${costPerHourSavedCny.toFixed(0)}，高于当前计算时薪 ¥${appliedHourlyRateCny.toFixed(0)}/h，除非用于关键精力恢复否则可省下`
      : '请输入预计节省的分钟数',
    detailEn: Number.isFinite(costPerHourSavedCny)
      ? `Costs ¥${costPerHourSavedCny.toFixed(0)}/h saved, above your ¥${appliedHourlyRateCny.toFixed(0)}/h benchmark`
      : 'Enter saved minutes to evaluate',
  };
}

export function computeFocusSessionValue(
  elapsedSeconds: number,
  category: TimeBlockCategory,
  breakdown: HourlyRateBreakdown,
): { valueCny: number; appliedHourlyCny: number; rateLabelZh: string; rateLabelEn: string } {
  const safeSeconds = clampNonNegative(elapsedSeconds, 0);
  const hours = safeSeconds / 3600;

  let appliedHourlyCny = breakdown.trueNetHourlyCny;
  let rateLabelZh = '真实净时薪';
  let rateLabelEn = 'True Net Rate';

  if (category === 'study' || category === 'deep-work' || category === 'fitness') {
    appliedHourlyCny = breakdown.focusCompoundHourlyCny;
    rateLabelZh = '深度复利时薪';
    rateLabelEn = 'Compound Focus Rate';
  }

  const valueCny = Math.round(hours * appliedHourlyCny * 100) / 100;
  return {
    valueCny,
    appliedHourlyCny,
    rateLabelZh,
    rateLabelEn,
  };
}

export function computeDailyTimeValueLedger(
  blocks: readonly TimeBlockItem[],
  breakdown: HourlyRateBreakdown,
  activeTimerElapsedSeconds = 0,
  activeTimerCategory: TimeBlockCategory = 'study',
): DailyTimeValueLedger {
  let studyMinutes = 0;
  let deepWorkMinutes = 0;
  let fitnessMinutes = 0;
  let lifeMinutes = 0;
  let restMinutes = 0;

  for (const b of blocks) {
    const dur = Math.max(0, b.durationMinutes || 0);
    if (b.category === 'study') studyMinutes += dur;
    else if (b.category === 'deep-work') deepWorkMinutes += dur;
    else if (b.category === 'fitness') fitnessMinutes += dur;
    else if (b.category === 'life') lifeMinutes += dur;
    else if (b.category === 'rest') restMinutes += dur;
  }

  const totalTrackedMinutes =
    studyMinutes + deepWorkMinutes + fitnessMinutes + lifeMinutes + restMinutes;

  const liveSession = computeFocusSessionValue(
    activeTimerElapsedSeconds,
    activeTimerCategory,
    breakdown,
  );

  const compoundMinutes = studyMinutes + deepWorkMinutes + fitnessMinutes;
  const compoundValue = (compoundMinutes / 60) * breakdown.focusCompoundHourlyCny;
  const lifeValue = (lifeMinutes / 60) * breakdown.trueNetHourlyCny;

  const totalValueCreatedCny =
    Math.round((compoundValue + lifeValue + Math.max(0, liveSession.valueCny)) * 100) / 100;

  const headlineZh =
    breakdown.trueNetHourlyCny > 0
      ? `今日专注与创造累计价值 +¥${totalValueCreatedCny.toFixed(1)}（精进 ${compoundMinutes}m）`
      : '设定真实净时薪，开启 24H 时间价值账单';
  const headlineEn =
    breakdown.trueNetHourlyCny > 0
      ? `Today Focus Value +¥${totalValueCreatedCny.toFixed(1)} (${compoundMinutes}m compound)`
      : 'Set true hourly rate to unlock 24H time value ledger';

  return {
    studyMinutes,
    deepWorkMinutes,
    fitnessMinutes,
    lifeMinutes,
    restMinutes,
    totalTrackedMinutes,
    totalValueCreatedCny,
    liveTimerValueCny: liveSession.valueCny,
    headlineZh,
    headlineEn,
  };
}
